<p><b>逐字拆解。</b></p>
<ul>
<li><b>"在 $x_0$ 的某邻域内有定义"</b>：要求 $x_0$ 左右两侧都有函数值，即 $x_0$ 是定义域的<b>内点</b>。因此闭区间 $[a,b]$ 的端点 $a,b$ <b>永远不是</b>定义在 $[a,b]$ 上的函数的极值点（左边或右边没有点可比）。这一条正是罗尔定理证明中必须把最值点"挤"到区间内部的原因。</li>
