<li><b>"唯一确定"</b>：一个 $x$ 只对应一个 $y$（单值性）。几何上就是<b>竖直线检验</b>：任何竖直线与函数图像至多一个交点。圆 $x^2+y^2=1$ 不是"$y$ 关于 $x$ 的函数"，因为竖直线 $x=0$ 与它交于 $(0,1)$、$(0,-1)$ 两点。</li>
